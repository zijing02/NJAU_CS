;1．编辑以下程序，汇编连接后运行，将得到X+|Y|-|Z|的值输出’。 
DATA SEGMENT
   INPUT DB 'X=20,Y=24,Z=-42',0DH,0AH,'X+|Y|-|Z|=$'
	X DB 20H
	Y DB 24H
	Z DB -42H
DATA ENDS

STACK SEGMENT
    DB 200 DUP(0)
STACK ENDS

CODE SEGMENT
    ASSUME CS:CODE,DS:DATA,SS:STACK
BEGIN:
    MOV AX,DATA
	MOV DS,AX
	MOV AX,STACK
	MOV SS,AX
	LEA DX,INPUT
	MOV AH,09H
	INT 21H
	MOV AL,X
	CMP Y,0
	JGE  L0
    MOV BL,Y
	DEC BL
	NOT BL
	MOV Y,BL
L0:
    ADD AL,Y
	CMP Z,0
	JGE L1
    MOV BL,Z
	DEC BL
	NOT BL
	MOV Z,BL
L1:
    SUB AL,Z
	MOV DL,AL
	ADD DL,30H
	MOV AH,2
	INT 21H
	MOV AH,4CH
	INT 21H
CODE ENDS
    END BEGIN